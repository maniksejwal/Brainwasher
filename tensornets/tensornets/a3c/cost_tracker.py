"""
tensornets.a3c.cost_tracker — Per-turn LLM cost and token tracking.

Accumulates token counts and cost estimates across every LLM call made within
a single episode.  Each arm uses a different mix of Scout / Maverick calls:

    Exp 0  physio_llm            : 1 Scout call per turn
    Exp 1  physio_llm_cot_mcts   : 1 Maverick CoT call + 1 Scout call per turn
    Exp 2  physio_mps_mcts       : 1 Scout call per turn  (+ MCTS HTTP, no LLM)
    Exp 3  inertial_physio_mps_mcts : 1 Scout call per turn
    Exp 4  inertial_physio_llm_cot_mcts : 1 Maverick CoT + 1 Scout per turn
    Exp 5  oldschool             : JS handles LLM calls; tokens not tracked here

Per-token rates (USD) from tensornets.training.judge (Bedrock on-demand pricing):
    Scout    input: $0.00017 / 1K tokens    output: $0.00060 / 1K tokens
    Maverick input: $0.00022 / 1K tokens    output: $0.00088 / 1K tokens

No fallbacks.  Callers must pass valid model strings and non-negative token counts.
ValueError is raised immediately for any invalid input.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Literal

# ── Per-token pricing (Bedrock on-demand, USD per 1K tokens) ─────────────────

ModelKey = Literal["scout", "maverick"]

_RATE_IN:  dict[ModelKey, float] = {
    "scout":    0.00017,
    "maverick": 0.00022,
}
_RATE_OUT: dict[ModelKey, float] = {
    "scout":    0.00060,
    "maverick": 0.00088,
}


def _cost_usd(model: ModelKey, tokens_in: int, tokens_out: int) -> float:
    """Calculate cost in USD for one LLM call."""
    return (tokens_in / 1000.0) * _RATE_IN[model] + (tokens_out / 1000.0) * _RATE_OUT[model]


@dataclass
class TurnCost:
    """Cost record for a single LLM call within a turn."""
    model:      ModelKey
    tokens_in:  int
    tokens_out: int
    cost_usd:   float
    latency_ms: float


@dataclass
class CostTracker:
    """
    Accumulates token and cost data across all LLM calls in one episode.

    Usage
    -----
        tracker = CostTracker()
        record  = tracker.record("scout", tokens_in=80, tokens_out=120, latency_ms=340.0)
        summary = tracker.episode_summary()
    """

    _turns: list[TurnCost] = field(default_factory=list, init=False)

    def record(
        self,
        model: str,
        tokens_in: int,
        tokens_out: int,
        latency_ms: float,
    ) -> TurnCost:
        """
        Record one LLM call and return a TurnCost.

        Parameters
        ----------
        model      : "scout" or "maverick"
        tokens_in  : Prompt tokens (input to the model).
        tokens_out : Completion tokens (generated by the model).
        latency_ms : Wall-clock time for this call in milliseconds.

        Raises
        ------
        ValueError
            If model is unknown, or token counts are negative.
        """
        if model not in _RATE_IN:
            raise ValueError(
                f"CostTracker.record: unknown model '{model}'. "
                f"Valid values: {sorted(_RATE_IN)}. "
                f"Add new models with their per-token rates to cost_tracker.py."
            )
        if tokens_in < 0 or tokens_out < 0:
            raise ValueError(
                f"CostTracker.record: token counts must be non-negative, "
                f"got tokens_in={tokens_in}, tokens_out={tokens_out} for model='{model}'."
            )
        if latency_ms < 0.0:
            raise ValueError(
                f"CostTracker.record: latency_ms must be non-negative, got {latency_ms}."
            )
        cost = _cost_usd(model, tokens_in, tokens_out)  # type: ignore[arg-type]
        tc = TurnCost(
            model=model,  # type: ignore[arg-type]
            tokens_in=tokens_in,
            tokens_out=tokens_out,
            cost_usd=round(cost, 8),
            latency_ms=round(latency_ms, 1),
        )
        self._turns.append(tc)
        return tc

    # ── Per-turn aggregates (for the most recent set of calls in one turn) ───

    def turn_summary(self, n_calls: int = 1) -> dict:
        """
        Return aggregated stats for the last n_calls records.
        Used to populate EpisodeTurn.cost fields.
        """
        if not self._turns:
            raise RuntimeError(
                "CostTracker.turn_summary called before any record() calls."
            )
        recent = self._turns[-n_calls:]
        return {
            "cost_usd":    round(sum(r.cost_usd for r in recent), 8),
            "tokens_in":   sum(r.tokens_in  for r in recent),
            "tokens_out":  sum(r.tokens_out for r in recent),
            "llm_calls":   len(recent),
            "latency_ms":  round(sum(r.latency_ms for r in recent), 1),
        }

    def episode_summary(self) -> dict:
        """
        Return total cost/token stats for the completed episode.
        Included in genuine_metrics and posted to the DB.
        """
        if not self._turns:
            return {
                "cost_usd_total":    0.0,
                "tokens_in_total":   0,
                "tokens_out_total":  0,
                "llm_calls_total":   0,
                "cost_per_turn_avg": 0.0,
            }
        n = len(self._turns)
        total_cost = sum(r.cost_usd for r in self._turns)
        return {
            "cost_usd_total":    round(total_cost, 6),
            "tokens_in_total":   sum(r.tokens_in  for r in self._turns),
            "tokens_out_total":  sum(r.tokens_out for r in self._turns),
            "llm_calls_total":   n,
            "cost_per_turn_avg": round(total_cost / n, 8) if n else 0.0,
        }

    def __len__(self) -> int:
        return len(self._turns)
