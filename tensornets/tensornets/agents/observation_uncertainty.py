"""
observation_uncertainty.py — OBS1-OBS5: Human observation failure model.

Background
----------
MCTS and A3C both treat `state` as ground truth.  In reality, every piece of
patient-reported information is an *observation generated by a fallible human
state*.  The same event can be reported differently depending on:

  forgetfulness       — the patient omitted something they actually know
  misinterpretation   — they understood an event incorrectly
  incomplete_info     — they genuinely don't know
  false_confidence    — low-quality belief reported with high certainty
  self_uncertainty    — they know they may be wrong (honest signal)
  systematic_bias     — interpretation is consistently distorted (e.g. catastrophising)
  recall_distortion   — memory of a past event has shifted over time
  attention_failure   — something relevant was not noticed at all
  communication_fail  — what they meant != what another participant understood
  strategic_concealment — information is deliberately withheld
  state_dependent     — stress / fear / pain changes their assessment in this moment

This module:
  1. Provides `ObservationUncertainty` — per-turn probability estimates for each mode.
  2. Provides `update_from_scorer()` — updates weights from A3CScorer distortion signals.
  3. Provides `credibility_weight()` — aggregate trustworthiness of the current state [0,1].
  4. Provides `mcts_uncertainty_modifier()` — adjusts MCTS exploration constant for uncertainty.
  5. Provides `robust_action_score()` — discounts high-specificity actions when uncertainty is high.

Design constraints
------------------
- No extra LLM calls.  All updates come from the A3CScorer output (which is already called
  every N turns) and from BeliefGraph confidence divergence.
- Never blocks training.  All update paths are wrapped in try/except.
- Serialisable to/from dict for persistence in run_state.json.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    pass   # BeliefGraph imported lazily to avoid circular deps

__all__ = [
    "ObservationUncertainty",
    "DISTORTION_MODES",
    "update_from_scorer_signals",
]

# ── Distortion mode registry ──────────────────────────────────────────────────

DISTORTION_MODES: list[str] = [
    "forgetfulness",
    "misinterpretation",
    "incomplete_info",
    "false_confidence",
    "self_uncertainty",
    "systematic_bias",
    "recall_distortion",
    "attention_failure",
    "communication_fail",
    "strategic_concealment",
    "state_dependent",
]

# Weights for credibility penalty calculation.
# Modes where the patient KNOWS something but mis-reports it (deceptive or distorted)
# are more damaging to state reliability than honest-uncertainty modes.
_CREDIBILITY_WEIGHTS: dict[str, float] = {
    "forgetfulness":        0.6,   # benign; partially recoverable from context
    "misinterpretation":    0.8,   # moderate; often detectable via probe
    "incomplete_info":      0.3,   # honest gap — least damaging
    "false_confidence":     1.2,   # dangerous: wrong but certain
    "self_uncertainty":     0.2,   # honest uncertainty — near-zero penalty
    "systematic_bias":      1.0,   # hard to correct without belief work
    "recall_distortion":    0.7,   # memory shifts — moderate
    "attention_failure":    0.5,   # something missed — often recoverable
    "communication_fail":   0.9,   # shared misunderstanding — cascades
    "strategic_concealment": 1.5,  # deliberate — highest penalty
    "state_dependent":      0.8,   # situational; resolves when stress drops
}

# MCTS exploration boost when uncertainty is high.
# Uncertainty ≥ 0.7 credibility → expand C by up to _MAX_C_BOOST.
_MAX_C_BOOST: float = 0.4

# Minimum credibility floor (system never assumes zero reliability).
_MIN_CREDIBILITY: float = 0.15


# ── Core dataclass ───────────────────────────────────────────────────────────

@dataclass
class ObservationUncertainty:
    """
    Per-turn probability weights for each human observation distortion mode.

    Each field is P(mode is currently active) ∈ [0, 1].
    Defaults reflect a baseline therapeutic first-contact:
      - Some incompleteness (0.25) is universal
      - State-dependent distortion (0.20) is common under clinical stress
      - Strategic concealment (0.05) is rare in genuine help-seeking

    Attributes are updated per turn by `update_from_scorer_signals()` using signals
    the A3CScorer already produces:
      contradiction detected → raises false_confidence + strategic_concealment
      low info_novelty       → raises forgetfulness + attention_failure
      high stress physio     → raises state_dependent + systematic_bias
      probing_question pass  → lowers incomplete_info (patient is opening up)
      topic avoidance        → raises strategic_concealment + attention_failure
    """
    forgetfulness:          float = 0.10
    misinterpretation:      float = 0.10
    incomplete_info:        float = 0.25
    false_confidence:       float = 0.10
    self_uncertainty:       float = 0.20
    systematic_bias:        float = 0.10
    recall_distortion:      float = 0.10
    attention_failure:      float = 0.05
    communication_fail:     float = 0.10
    strategic_concealment:  float = 0.05
    state_dependent:        float = 0.20

    # Session-level accumulators for trend detection (not per-turn probabilities).
    _contradiction_count:   int   = field(default=0, repr=False)
    _avoidance_count:       int   = field(default=0, repr=False)
    _probe_success_count:   int   = field(default=0, repr=False)

    # ── Aggregate reliability ─────────────────────────────────────────────────

    def credibility_weight(self) -> float:
        """
        Aggregate trustworthiness of current state observations, ∈ [0.15, 1.0].

        Formula: 1 − weighted_sum(P(mode) × penalty_weight(mode)) / normaliser

        Honest-uncertainty modes (self_uncertainty, incomplete_info) contribute
        positively — a patient who says "I'm not sure" is MORE credible than one
        who reports everything with false certainty.

        Returns
        -------
        float : 1.0 = fully credible; 0.15 = near-unreliable.
        """
        weighted_sum = 0.0
        for mode, w in _CREDIBILITY_WEIGHTS.items():
            p = getattr(self, mode, 0.0)
            weighted_sum += p * w

        # Honest uncertainty is a positive signal — subtract its weighted contribution
        honesty_bonus = (
            self.self_uncertainty * _CREDIBILITY_WEIGHTS["self_uncertainty"] +
            self.incomplete_info  * _CREDIBILITY_WEIGHTS["incomplete_info"]
        )
        penalty = max(0.0, weighted_sum - honesty_bonus)
        raw = 1.0 - (penalty / (len(DISTORTION_MODES) * 0.8))
        return round(max(_MIN_CREDIBILITY, min(1.0, raw)), 4)

    def mcts_uncertainty_modifier(self) -> float:
        """
        Additional UCB exploration constant boost for MCTS when credibility is low.

        When the patient's reported state is unreliable, MCTS should explore more
        broadly (try meta-actions like normalise_discrepancy, seek_probe_consent)
        rather than exploiting a possibly-wrong state estimate.

        Returns a non-negative additive boost to the MCTS UCB constant C.
        """
        cred = self.credibility_weight()
        if cred >= 0.85:
            return 0.0
        # Boost rises linearly from 0 at cred=0.85 to _MAX_C_BOOST at cred=_MIN_CREDIBILITY
        slope = _MAX_C_BOOST / (0.85 - _MIN_CREDIBILITY)
        return round(min(_MAX_C_BOOST, slope * (0.85 - cred)), 4)

    def robust_action_discount(self, stress_specificity: float) -> float:
        """
        Discount factor for high-specificity actions when observation is uncertain.

        An action with high stress_specificity (e.g. 'graded_imagery' only works
        at moderate stress) should be penalised more heavily when we don't know
        whether the patient's reported stress is accurate.

        Parameters
        ----------
        stress_specificity : float [0, 1] — 0 = works in any state,
                             1 = only works in a narrow stress window.

        Returns
        -------
        float in [0, 1] — multiply action Q-value by this factor.
        """
        cred = self.credibility_weight()
        return round(1.0 - (1.0 - cred) * stress_specificity, 4)

    def dominant_modes(self, top_n: int = 3) -> list[tuple[str, float]]:
        """Return the top-N most active distortion modes by probability."""
        modes = [
            (m, getattr(self, m, 0.0))
            for m in DISTORTION_MODES
        ]
        return sorted(modes, key=lambda x: x[1], reverse=True)[:top_n]

    def prompt_context(self) -> str:
        """
        One-line hint for the companion's context block.

        Only injected when credibility is meaningfully below 1.0.
        Tells the companion WHY the patient's state may be unreliable and
        which meta-actions should be used to reduce uncertainty.
        """
        cred = self.credibility_weight()
        if cred >= 0.85:
            return ""

        top = self.dominant_modes(top_n=2)
        mode_labels = {
            "forgetfulness":         "patient may have omitted relevant history",
            "misinterpretation":     "patient may have misread a past event",
            "incomplete_info":       "patient may not have full picture",
            "false_confidence":      "patient may be reporting beliefs with unwarranted certainty",
            "self_uncertainty":      "patient is aware they may be wrong",
            "systematic_bias":       "patient's interpretation may be systematically distorted",
            "recall_distortion":     "patient's memory of the event may have shifted",
            "attention_failure":     "patient may have missed something relevant",
            "communication_fail":    "what patient said may not be what they meant",
            "strategic_concealment": "patient may be selectively withholding",
            "state_dependent":       "patient's current stress is distorting their assessment",
        }
        flags = [f"{mode_labels.get(m, m)} ({p:.0%})" for m, p in top if p > 0.12]
        if not flags:
            return ""

        # Which actions can reduce uncertainty?
        meta_actions: list[str] = []
        if self.strategic_concealment > 0.15 or self.false_confidence > 0.15:
            meta_actions.append("normalise_discrepancy")
        if self.incomplete_info > 0.20 or self.self_uncertainty > 0.25:
            meta_actions.append("seek_probe_consent")
        if self.misinterpretation > 0.15 or self.recall_distortion > 0.15:
            meta_actions.append("open_question")
        if self.communication_fail > 0.15:
            meta_actions.append("reflective_listening")

        hint = (
            f"[Observation Reliability: {cred:.0%}] "
            f"Flags: {'; '.join(flags)}. "
        )
        if meta_actions:
            hint += f"Recommended: {', '.join(meta_actions[:2])} before accepting state as fact."
        return hint

    # ── Serialisation ─────────────────────────────────────────────────────────

    def to_dict(self) -> dict:
        return {m: getattr(self, m) for m in DISTORTION_MODES} | {
            "_contradiction_count": self._contradiction_count,
            "_avoidance_count":     self._avoidance_count,
            "_probe_success_count": self._probe_success_count,
        }

    @classmethod
    def from_dict(cls, d: dict) -> "ObservationUncertainty":
        obj = cls()
        for m in DISTORTION_MODES:
            if m in d:
                setattr(obj, m, float(d[m]))
        obj._contradiction_count = int(d.get("_contradiction_count", 0))
        obj._avoidance_count     = int(d.get("_avoidance_count", 0))
        obj._probe_success_count = int(d.get("_probe_success_count", 0))
        return obj


# ── Update function ───────────────────────────────────────────────────────────

_ALPHA_OBS = 0.15   # EWA learning rate for probability updates

def _ewa_update(current: float, target: float) -> float:
    """Exponential moving average update toward target."""
    return round(max(0.0, min(1.0, current + _ALPHA_OBS * (target - current))), 4)


def update_from_scorer_signals(
    obs: ObservationUncertainty,
    scorer_signals: dict,
    stress_index:   float = 0.5,
) -> ObservationUncertainty:
    """
    Update ObservationUncertainty from A3CScorer output signals.

    INDEPENDENCE PRINCIPLE
    ----------------------
    The A3CScorer evaluates two *independent* things:
      (1) Agent quality  — did the companion respond well?
                           Fields: commitment_contradiction_score, consent_respect_score,
                                   generic_score, goal_progress, escalation_quality_score.
                           These drive A3C reward.  Do NOT read them here.
      (2) Patient reliability — does the patient's self-report show distortion?
                           Fields: obs_contradiction_score, obs_avoidance_score,
                                   obs_confidence_mismatch, obs_distortion_modes.
                           These are the ONLY inputs to ObservationUncertainty.
                           These drive MCTS exploration and action discounting.

    Mixing these two dimensions would mean: "the agent said something inconsistent
    → therefore the patient is being deceptive." That is logically wrong and would
    corrupt both the A3C gradient (agent quality) and the OBS model (patient reliability).

    Reads fields that the A3CScorer produces specifically for patient-side distortion:
      obs_contradiction_score    int: -2 to 0  — patient self-contradiction
      obs_avoidance_score        int: -2 to 0  — patient topic avoidance
      obs_confidence_mismatch    float: 0.0–1.0 — patient overconfidence vs evidence
      obs_distortion_modes       list[str]: active modes explicitly flagged by scorer
      probing_score              int: 0–2  — companion question opened the patient up
      info_novelty               float: 0–1 — how much new info the patient disclosed

    Parameters
    ----------
    obs             : current ObservationUncertainty to update
    scorer_signals  : dict of A3CScorer JSON output fields
    stress_index    : patient's current stress [0,1] for state_dependent update
    """
    # ── Contradiction detected ────────────────────────────────────────────────
    contradiction = scorer_signals.get("obs_contradiction_score", 0)
    if contradiction < -1:
        obs._contradiction_count += 1
        obs.false_confidence    = _ewa_update(obs.false_confidence,    min(1.0, obs.false_confidence + 0.20))
        obs.systematic_bias     = _ewa_update(obs.systematic_bias,     min(1.0, obs.systematic_bias + 0.10))
        if obs._contradiction_count >= 3:
            obs.strategic_concealment = _ewa_update(obs.strategic_concealment, min(0.8, obs.strategic_concealment + 0.15))
    elif contradiction == 0:
        obs.false_confidence    = _ewa_update(obs.false_confidence,    max(0.0, obs.false_confidence - 0.05))

    # ── Topic avoidance ───────────────────────────────────────────────────────
    avoidance = scorer_signals.get("obs_avoidance_score", 0)
    if avoidance < -1:
        obs._avoidance_count += 1
        obs.strategic_concealment = _ewa_update(obs.strategic_concealment, min(0.7, obs.strategic_concealment + 0.12))
        obs.attention_failure     = _ewa_update(obs.attention_failure,     min(0.5, obs.attention_failure + 0.08))
    elif avoidance >= 0:
        obs.strategic_concealment = _ewa_update(obs.strategic_concealment, max(0.0, obs.strategic_concealment - 0.03))

    # ── Confidence mismatch (patient stated certain but facts suggest uncertain) ──
    conf_mismatch = float(scorer_signals.get("obs_confidence_mismatch", 0.0))
    obs.false_confidence    = _ewa_update(obs.false_confidence,    obs.false_confidence + conf_mismatch * 0.15)
    obs.recall_distortion   = _ewa_update(obs.recall_distortion,   obs.recall_distortion + conf_mismatch * 0.10)

    # ── Explicit distortion mode flags from scorer ────────────────────────────
    active_modes: list[str] = scorer_signals.get("obs_distortion_modes", [])
    for mode in DISTORTION_MODES:
        if mode in active_modes:
            setattr(obs, mode, _ewa_update(getattr(obs, mode), min(0.9, getattr(obs, mode) + 0.20)))
        else:
            # Slow decay toward prior when mode is not flagged
            prior = ObservationUncertainty.__dataclass_fields__[mode].default  # type: ignore[attr-defined]
            setattr(obs, mode, _ewa_update(getattr(obs, mode), prior * 0.95))

    # ── Probing question success → reduces incomplete_info ───────────────────
    probing = scorer_signals.get("probing_score", 0)
    if probing > 0:
        obs._probe_success_count += 1
        obs.incomplete_info = _ewa_update(obs.incomplete_info, max(0.05, obs.incomplete_info - 0.10 * probing))
        obs.self_uncertainty = _ewa_update(obs.self_uncertainty, max(0.05, obs.self_uncertainty - 0.05))

    # ── State-dependent: directly tracks physiological stress ────────────────
    # High stress → state_dependent rises; low stress → decays toward baseline.
    target_sd = 0.10 + 0.50 * max(0.0, stress_index - 0.40)
    obs.state_dependent = _ewa_update(obs.state_dependent, target_sd)

    # ── Low info_novelty → possible forgetfulness or attention failure ────────
    novelty = float(scorer_signals.get("info_novelty", 0.5))
    if novelty < 0.2:
        obs.forgetfulness    = _ewa_update(obs.forgetfulness,    min(0.6, obs.forgetfulness + 0.08))
        obs.attention_failure = _ewa_update(obs.attention_failure, min(0.5, obs.attention_failure + 0.05))

    return obs


# ── Topic detection: LLM-first, no keyword hardcoding ────────────────────────
# Replaces the keyword-based detect_topic_from_text for all languages including
# English.  Called from social_alliance.py — imported lazily to avoid circulars.

_TOPIC_LIST = [
    "health", "mental_health", "finances", "family",
    "work", "intimacy", "conflict", "grief", "identity", "future",
]

_TOPIC_DETECT_SYSTEM = (
    "You are a clinical conversation topic classifier. "
    "Rate each topic's relevance to the provided text on a scale of 0.00–0.20. "
    "Output ONLY a valid JSON object. No prose, no code fences."
)

_TOPIC_DETECT_PROMPT = (
    "Text: {text}\n\n"
    "Rate the relevance of each clinical topic (0.00 = not mentioned, "
    "0.20 = primary focus):\n"
    "{topic_list}\n\n"
    "Return exactly: {{\"health\": 0.0, \"mental_health\": 0.0, "
    "\"finances\": 0.0, \"family\": 0.0, \"work\": 0.0, \"intimacy\": 0.0, "
    "\"conflict\": 0.0, \"grief\": 0.0, \"identity\": 0.0, \"future\": 0.0}}"
)

_TOPIC_SALIENCE_MAX = 0.20


def detect_topic_llm(
    text:    str,
    arm:     str = "topic_detect",
    timeout: float = 8.0,
) -> dict[str, float]:
    """
    LLM-based topic detection — language agnostic, no keyword lists.

    Uses a single lightweight Scout call.  Returns {topic: salience} with
    values capped at _TOPIC_SALIENCE_MAX.  Falls back to empty dict on any
    error (non-blocking; training continues without topic coupling updates).

    This replaces keyword-based matching entirely.  The LLM understands:
    - All languages and scripts (code-switching, romanised Hindi, Arabic, etc.)
    - Idioms and indirect references ("things have been tight" → finances)
    - Mixed-language utterances ("main bahut stressed hoon about my job")
    """
    if not text or not text.strip():
        return {}
    try:
        import json as _json
        from tensornets.node_client import NodeClient as _NC
        _client = _NC()
        prompt  = _TOPIC_DETECT_PROMPT.format(
            text       = text[:500],
            topic_list = "\n".join(f"  {t}" for t in _TOPIC_LIST),
        )
        resp = _client.llm_call(
            system  = _TOPIC_DETECT_SYSTEM,
            user    = prompt,
            arm     = arm,
            timeout = timeout,
        )
        raw = resp.get("content", "{}").strip()
        raw = raw.lstrip("```json").lstrip("```").rstrip("```").strip()
        parsed = _json.loads(raw)
        return {
            t: round(min(_TOPIC_SALIENCE_MAX, max(0.0, float(v))), 4)
            for t, v in parsed.items()
            if t in _TOPIC_LIST
        }
    except Exception:
        return {}


def _scout_call_sync(prompt: str, timeout: float = 12.0) -> str:
    """
    Minimal synchronous Scout (LLM) call helper.

    Wraps NodeClient.llm_call so other modules (e.g. social_alliance.py's
    update_coupling_from_belief_turn) can call Scout without importing
    NodeClient directly.

    Returns the raw text content, or "" on any error.
    """
    if not prompt:
        return ""
    try:
        from tensornets.node_client import NodeClient as _NC
        _client = _NC()
        resp = _client.llm_call(
            system  = "You are a precise JSON-only assistant.",
            user    = prompt,
            arm     = "belief_topic_coupling",
            timeout = timeout,
        )
        return resp.get("content", "")
    except Exception:
        return ""
